'use strict';
/* Minimal structured-content -> PDF engine on pdfkit.
 * Blocks: {h1},{h2},{h3},{p},{ul:[]},{ol:[]},{code},{table:{head,rows,widths}},{note},{warn},{caption},{diagram:fn,h,cap},{pb}
 * Inline **bold** is supported in p/ul/ol/table cells. Text must be WinAnsi-safe (ASCII + a few symbols). */
const PDFDocument = require('pdfkit');
const fs = require('fs');

const C = { ink: '#1f2933', mute: '#5f6b7a', accent: '#0b5cad', accent2: '#e8f1fb', rule: '#d5dbe3', codeBg: '#f3f5f8', warn: '#fff4e5', warnLine: '#d9822b', note: '#eaf6ee', noteLine: '#2f8f5b' };
const M = { l: 54, r: 54, t: 54, b: 78 };
const FOOT1 = 'Generated by AI. AI can make mistakes. Validate before relying upon this document.';
const FOOT2 = '© 2026 Cotiviti, Inc. All rights reserved. All proprietary information shall remain the sole and exclusive property of Cotiviti, Inc.';

function clean(s) {
  return String(s).replace(/[‘’]/g, "'").replace(/[“”]/g, '"').replace(/[–—]/g, '-').replace(/→/g, '->').replace(/≤/g, '<=').replace(/≥/g, '>=').replace(/×/g, 'x').replace(/•/g, '-').replace(/[^\x09\x0A\x20-\x7E\xA0-\xFF]/g, '?');
}

function render(opts, blocks, tocPages) {
  const doc = new PDFDocument({ size: 'A4', margins: { top: M.t, bottom: M.b, left: M.l, right: M.r }, bufferPages: true, info: { Title: opts.title, Author: 'Generated by AI (Claude)', Subject: opts.subtitle } });
  const W = doc.page.width - M.l - M.r;
  const headings = [];
  let figNo = 0;

  const bottom = () => doc.page.height - M.b;
  const ensure = (h) => { if (doc.y + h > bottom()) doc.addPage(); };

  function rich(text, x, y, width, size, font, color, extra) {
    // inline bold with **...**; segments are chained with continued:true so wrapping stays correct
    const parts = clean(text).split('**').map((t, i) => ({ t, bold: i % 2 === 1 })).filter((p) => p.t !== '');
    doc.fontSize(size).fillColor(color || C.ink);
    parts.forEach((p, i) => {
      doc.font(p.bold ? 'Helvetica-Bold' : font);
      const opts = Object.assign({ width, continued: i < parts.length - 1, lineGap: 2 }, extra);
      if (i === 0) doc.text(p.t, x, y, opts); else doc.text(p.t, opts);
    });
    doc.font(font);
  }
  function heightOfRich(text, width, size, font) {
    doc.font(font).fontSize(size);
    return doc.heightOfString(clean(text).replace(/\*\*/g, ''), { width, lineGap: 2 });
  }

  // ---------------- cover
  doc.rect(0, 0, doc.page.width, 250).fill(C.accent);
  doc.fillColor('#ffffff').font('Helvetica-Bold').fontSize(30).text(clean(opts.title), M.l, 90, { width: W });
  doc.font('Helvetica').fontSize(14).text(clean(opts.subtitle), M.l, doc.y + 10, { width: W });
  doc.fillColor(C.ink).font('Helvetica').fontSize(11);
  doc.y = 290;
  opts.coverLines.forEach((l) => { doc.font(l.bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(l.size || 11).fillColor(l.color || C.ink).text(clean(l.text), M.l, doc.y, { width: W, lineGap: 3 }); doc.moveDown(0.5); });
  doc.addPage();

  // ---------------- TOC placeholder pages
  const tocStart = doc.bufferedPageRange().count - 1;
  const tocEntries = tocPages || [];
  doc.font('Helvetica-Bold').fontSize(20).fillColor(C.accent).text('Contents', M.l, M.t);
  doc.moveDown(0.6);
  tocEntries.forEach((e) => {
    ensure(16);
    const y = doc.y;
    doc.font(e.level === 1 ? 'Helvetica-Bold' : 'Helvetica').fontSize(e.level === 1 ? 10.5 : 9.5).fillColor(C.ink);
    doc.text(clean(e.text), M.l + (e.level === 1 ? 0 : 16), y, { width: W - 50, lineBreak: false, ellipsis: true });
    doc.text(String(e.page), M.l + W - 40, y, { width: 40, align: 'right' });
    doc.y = y + (e.level === 1 ? 15 : 13);
  });
  doc.addPage();
  const bodyStart = doc.bufferedPageRange().count - 1;

  // ---------------- body
  const block = {
    h1: (b) => { if (doc.y > M.t + 5) { if (bottom() - doc.y < 300) doc.addPage(); else doc.moveDown(1.5); } headings.push({ level: 1, text: b.h1, pageIdx: doc.bufferedPageRange().count - 1 });
      doc.font('Helvetica-Bold').fontSize(20).fillColor(C.accent).text(clean(b.h1), M.l, doc.y, { width: W });
      doc.moveTo(M.l, doc.y + 4).lineTo(M.l + W, doc.y + 4).strokeColor(C.accent).lineWidth(1.2).stroke(); doc.moveDown(0.9); },
    h2: (b) => { ensure(60); headings.push({ level: 2, text: b.h2, pageIdx: doc.bufferedPageRange().count - 1 });
      doc.moveDown(0.5); doc.font('Helvetica-Bold').fontSize(13.5).fillColor(C.ink).text(clean(b.h2), M.l, doc.y, { width: W }); doc.moveDown(0.3); },
    h3: (b) => { ensure(40); doc.moveDown(0.3); doc.font('Helvetica-Bold').fontSize(11).fillColor(C.accent).text(clean(b.h3), M.l, doc.y, { width: W }); doc.moveDown(0.2); },
    p: (b) => { ensure(heightOfRich(b.p, W, 10, 'Helvetica') + 6 > 60 ? 40 : heightOfRich(b.p, W, 10, 'Helvetica') + 6); rich(b.p, M.l, doc.y, W, 10, 'Helvetica', C.ink); doc.moveDown(0.5); },
    ul: (b) => { b.ul.forEach((t) => { ensure(24); const y = doc.y; doc.font('Helvetica').fontSize(10).fillColor(C.accent).text('-', M.l + 4, y, { width: 10 }); rich(t, M.l + 18, y, W - 18, 10, 'Helvetica', C.ink); doc.moveDown(0.2); }); doc.moveDown(0.3); },
    ol: (b) => { b.ol.forEach((t, i) => { ensure(24); const y = doc.y; doc.font('Helvetica-Bold').fontSize(10).fillColor(C.accent).text(`${i + 1}.`, M.l + 2, y, { width: 18 }); rich(t, M.l + 22, y, W - 22, 10, 'Helvetica', C.ink); doc.moveDown(0.2); }); doc.moveDown(0.3); },
    code: (b) => { const t = clean(b.code); doc.font('Courier').fontSize(8.2);
      const lines = t.split('\n'); let i = 0;
      while (i < lines.length) { const room = Math.max(1, Math.floor((bottom() - doc.y - 10) / 10.2)); if (room < 3) { doc.addPage(); continue; }
        const chunk = lines.slice(i, i + room); const h = chunk.length * 10.2 + 10; const y0 = doc.y;
        doc.rect(M.l, y0, W, h).fill(C.codeBg); doc.fillColor(C.ink).font('Courier').fontSize(8.2);
        chunk.forEach((ln, k) => doc.text(ln.length > 118 ? ln.slice(0, 117) + '~' : ln, M.l + 6, y0 + 5 + k * 10.2, { width: W - 12, lineBreak: false }));
        doc.y = y0 + h + 4; i += chunk.length; }
      doc.moveDown(0.4); },
    note: (b) => callout(b.note, C.note, C.noteLine, 'Note'),
    warn: (b) => callout(b.warn, C.warn, C.warnLine, 'Caution'),
    caption: (b) => { doc.font('Helvetica-Oblique').fontSize(8.8).fillColor(C.mute).text(clean(b.caption), M.l, doc.y, { width: W, align: 'center' }); doc.moveDown(0.8); },
    pb: () => doc.addPage(),
    table: (b) => table(b.table),
    diagram: (b) => { const h = b.h; ensure(h + 30); const y0 = doc.y; figNo += 1; b.diagram(doc, M.l, y0, W, C); doc.y = y0 + h + 4;
      doc.font('Helvetica-Oblique').fontSize(8.8).fillColor(C.mute).text(`Figure ${figNo}. ${clean(b.cap)}`, M.l, doc.y, { width: W, align: 'center' }); doc.moveDown(0.9); },
  };

  function callout(text, bg, line, label) {
    const h = heightOfRich(text, W - 24, 9.5, 'Helvetica') + 16; ensure(h + 6); const y0 = doc.y;
    doc.rect(M.l, y0, W, h).fill(bg); doc.rect(M.l, y0, 3, h).fill(line);
    rich(`**${label}:** ${text}`, M.l + 12, y0 + 8, W - 24, 9.5, 'Helvetica', C.ink); doc.y = y0 + h + 6;
  }

  function table(t) {
    const widths = (t.widths || t.head.map(() => 1)); const sum = widths.reduce((a, b) => a + b, 0); const cw = widths.map((w) => (w / sum) * W);
    const size = t.size || 8.6; const pad = 4;
    const rowH = (cells, bold) => Math.max(...cells.map((c, i) => heightOfRich(String(c), cw[i] - pad * 2, size, bold ? 'Helvetica-Bold' : 'Helvetica'))) + pad * 2;
    const drawRow = (cells, y, h, header, zebra) => {
      if (header) doc.rect(M.l, y, W, h).fill(C.accent); else if (zebra) doc.rect(M.l, y, W, h).fill('#f8fafc');
      let x = M.l; cells.forEach((c, i) => { rich(String(c), x + pad, y + pad, cw[i] - pad * 2, size, header ? 'Helvetica-Bold' : 'Helvetica', header ? '#ffffff' : C.ink); x += cw[i]; });
      doc.moveTo(M.l, y + h).lineTo(M.l + W, y + h).strokeColor(C.rule).lineWidth(0.5).stroke();
    };
    let hh = rowH(t.head, true); ensure(hh + 40); drawRow(t.head, doc.y, hh, true, false); doc.y += hh;
    t.rows.forEach((r, idx) => { const h = rowH(r, false); if (doc.y + h > bottom()) { doc.addPage(); hh = rowH(t.head, true); drawRow(t.head, doc.y, hh, true, false); doc.y += hh; } drawRow(r, doc.y, h, false, idx % 2 === 1); doc.y += h; });
    doc.moveDown(0.8);
  }

  blocks.forEach((b) => { const k = Object.keys(b).find((x) => block[x]); if (!k) throw new Error('unknown block ' + JSON.stringify(Object.keys(b))); block[k](b); });

  // ---------------- page footers on every page (mandatory two-line footer + page number)
  const range = doc.bufferedPageRange();
  for (let i = 0; i < range.count; i++) {
    doc.switchToPage(i);
    const y = doc.page.height - 56;
    doc.page.margins.bottom = 0;
    doc.moveTo(M.l, y - 6).lineTo(M.l + W, y - 6).strokeColor(C.rule).lineWidth(0.5).stroke();
    doc.font('Helvetica-Oblique').fontSize(7).fillColor(C.mute);
    doc.text(FOOT1, M.l, y, { width: W, align: 'left', lineBreak: false });
    doc.text(FOOT2, M.l, y + 10, { width: W, align: 'left', lineBreak: false });
    if (i > 0) doc.font('Helvetica').fontSize(8).text(`Page ${i + 1} of ${range.count}`, M.l, y + 24, { width: W, align: 'right', lineBreak: false });
  }
  const toc = headings.map((h) => ({ level: h.level, text: h.text, page: h.pageIdx + 1 }));
  return { doc, toc, bodyStart, tocStart };
}

function build(opts, blocks, outFile) {
  // pass 1: measure headings with an empty TOC of the right length, pass 2: real page numbers
  const first = render(opts, blocks, []);
  const placeholder = first.toc.map((t) => ({ ...t, page: 0 }));
  first.doc.end();
  // the TOC may need more than one page: render with placeholder to learn the final page numbers
  const second = render(opts, blocks, placeholder);
  const final = render(opts, blocks, second.toc);
  second.doc.end();
  // converge once more in case TOC length shifted pages
  const third = render(opts, blocks, final.toc);
  final.doc.end();
  const stream = fs.createWriteStream(outFile);
  third.doc.pipe(stream);
  third.doc.end();
  return new Promise((res) => stream.on('finish', () => res(third.toc.length)));
}

module.exports = { build, C };
